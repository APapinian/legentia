/// Ondalık sayı, Türkçe virgülle: 14 → "1,4".
fn decimal(tenths: u32) -> String {
    format!("{},{}", tenths / 10, tenths % 10)
}

/// Bayt → megabayt, bir ondalıkla: 1 572 864 → "1,5".
fn megabytes(bytes: u64) -> String {
    decimal((bytes * 10 / (1 << 20)) as u32)
}

