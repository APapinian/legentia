    #[test]
    fn numbers_use_turkish_conventions() {
        let footer = Msg::ReadingFooter {
            chapter: 2,
            chapters: 12,
            page: 3,
            pages: 9,
            percent: 17,
        };
        assert_eq!(tr(&footer), "Bölüm 2/12 · Sayfa 3/9 · %17");
        assert_eq!(tr(&Msg::Percent(45)), "%45");
        assert_eq!(tr(&Msg::Decimal { tenths: 14 }), "1,4");
        assert_eq!(tr(&Msg::Points { tenths: 96 }), "9,6 punto");
        let left = Msg::TimeLeft {
            footer: Box::new(Msg::PageNumber(3)),
            chapter: 45,
            book: 200,
        };
        assert_eq!(tr(&left), "Sayfa 3 · bölüm 45 dk · kitap 3 sa 20 dk");
        let progress = Msg::Progress {
            done: 3 << 19,
            total: Some(6 << 20),
        };
        assert_eq!(tr(&progress), "%25 · 1,5 / 6,0 MB");
    }
